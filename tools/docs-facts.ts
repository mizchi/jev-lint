import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_MODEL } from "../src/jev.ts";
import { collectRows } from "./rules-md.ts";

export function renderProjectFacts(cwd: string): string {
  const pkg = JSON.parse(readFileSync(resolve(cwd, "package.json"), "utf8"));
  const rows = collectRows(resolve(cwd, "rules"));
  const perfect = rows.filter((row) => row.score?.precision === 1 && row.score?.recall === 1).length;
  const counts = new Map<string, number>();
  for (const row of rows) counts.set(row.rule.languageDir!, (counts.get(row.rule.languageDir!) ?? 0) + 1);
  const languages = [...counts].sort(([a], [b]) => a.localeCompare(b))
    .map(([language, count]) => `- ${language}: ${count} ${count === 1 ? "rule" : "rules"}`).join("\n");
  return `# Current project facts

<!-- Generated by tools/docs-facts.ts from implementation and accepted rule fixtures. -->

## Rule catalog

The current catalog contains ${rows.length} rules across ${counts.size} language directories, with ${new Set(rows.map((row) => row.rule.id)).size} distinct rule IDs. ${perfect} rules reach precision and recall 1.00 on their own accepted fixtures. There are ${rows.reduce((n, r) => n + r.defects, 0)} labelled defects and ${rows.reduce((n, r) => n + r.cleans, 0)} labelled cleans. These are fixture measurements, not production accuracy.

${languages}

## Runtime

The package requires Node.js ${pkg.engines.node}. Its runtime dependencies are ${Object.keys(pkg.dependencies).sort().map((name) => `\`${name}\``).join(" and ")}.

## Default model

The default model is \`${DEFAULT_MODEL}\`. Explicit CLI, configuration and environment overrides still apply.

## CI

The local CI command is \`npm run ci\`. Its complete package script is:

\`\`\`sh
${pkg.scripts.ci}
\`\`\`

## Package contents

The package exports are:

${Object.keys(pkg.exports).map((name) => `- \`${name}\``).join("\n")}

The published files include:

${pkg.files.map((name: string) => `- \`${name}\``).join("\n")}
`;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const cwd = resolve(fileURLToPath(new URL("..", import.meta.url))), target = resolve(cwd, "docs/project-facts.md");
  const output = renderProjectFacts(cwd);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== output) throw new Error("project facts are stale; run just docs-facts");
    process.stdout.write("Project documentation facts are current\n");
  } else { writeFileSync(target, output); process.stdout.write("Updated docs/project-facts.md\n"); }
}
