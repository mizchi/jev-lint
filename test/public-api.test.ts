await testAsync("public-api includes declared Go embeddings and distinguishes aliases", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jev-api-embedded-"));
  try {
    writeFileSync(join(dir, "aliases.go"), "package api\nimport \"io\"\ntype Source = io.Reader\ntype Sink struct { io.Writer; private int }\ntype Channel interface { io.Reader; Close() error }");
    const out = join(dir, "out");
    const messages: string[] = [];
    assert.equal(await main(["public-api-inputs", out, dir], { out: () => {}, log: s => messages.push(s) }), 0, messages.join("\n"));
    const body = readFileSync(join(out, readdirSync(out)[0]), "utf8");
    assert.match(body, /type Source = io.Reader/);
    assert.match(body, /type Sink struct \{ io.Writer \}/);
    assert.match(body, /type Channel interface \{ .*io.Reader/);
    assert.doesNotMatch(body, /private/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
