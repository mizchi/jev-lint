import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { main } from "../src/cli/main.ts";
import { testAsync } from "./harness.ts";

await testAsync("public-api collects only reachable TS exports and package-level Go bindings", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jev-public-"));
  try {
    const file = (name: string, code: string) => writeFileSync(join(dir, name), code);
    file("lib.ts", "export function decode(x: string): number { return 123456; }\nexport const unused = 42;");
    file("barrel.ts", "export { decode as parse } from './lib.js';");
    file("public.ts", "// 日本語\nexport * from './barrel.js';\nexport default class Reader { private secret = 3; read(): string {return 'implementation';} }");
    mkdirSync(join(dir, "client"));
    file("client/client.go", `package client
type Client struct { secret string; Address string }
type hidden struct {}
func (c *Client) Read() error { return nil }
func (h *hidden) Leak() {}
var Alpha, Beta int
func Ångström() { type Local struct{} }
`);
    file("client/client_test.go", "package client\nfunc TestOnly() {}");
    const out = join(dir, "out");
    const messages: string[] = [];
    const code = await main(["public-api-inputs", out, join(dir, "public.ts"), join(dir, "client")], { out: () => {}, log: s => messages.push(s) });
    assert.equal(code, 0, messages.join("\n"));
    const ts = readFileSync(join(out, "1-public.ts.apisurface"), "utf8");
    assert.match(ts, /Public names: 2\b/);
    for (const name of ["parse", "default", "read"]) assert.ok(ts.includes(name), name);
    assert.doesNotMatch(ts, /unused|secret|123456|implementation/);
    const go = readFileSync(join(out, "2-client.apisurface"), "utf8");
    assert.match(go, /Public names: 5\b/);
    for (const name of ["Alpha", "Beta", "Client.Read", "Address", "Ångström"]) assert.ok(go.includes(name), name);
    assert.doesNotMatch(go, /TestOnly|secret|Local|Leak|return nil/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

await testAsync("public-api rejects an unresolved re-export without writing partial evidence", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jev-public-error-"));
  try {
    writeFileSync(join(dir, "index.ts"), "export * from './missing.js';");
    const errors: string[] = [];
    const out = join(dir, "out");
    assert.equal(await main(["public-api-inputs", out, join(dir, "index.ts")], { log: s => errors.push(s) }), 2);
    assert.match(errors.join(" "), /missing/);
    assert.equal(existsSync(out), false);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

await testAsync("public-api obeys Go build tags and records public variable types", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jev-api-tags-"));
  try {
    writeFileSync(join(dir, "base.go"), "package codec\nvar Registry map[string]int");
    writeFileSync(join(dir, "extra.go"), "//go:build jevlintunusedtag\n\npackage codec\nfunc Extra() {}");
    const out = join(dir, "out");
    const messages: string[] = [];
    assert.equal(await main(["public-api-inputs", out, dir], { out: () => {}, log: s => messages.push(s) }), 0, messages.join("\n"));
    const [file] = readdirSync(out);
    const body = readFileSync(join(out, file), "utf8");
    assert.match(body, /Public names: 1\nvar Registry map\[string\]int/);
    assert.doesNotMatch(body, /Extra/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

await testAsync("public-api retains late public members and identifies default aliases", async () => {
  const dir = mkdtempSync(join(tmpdir(), "jev-api-members-"));
  try {
    const fields = Array.from({length: 40}, (_, i) => "functionName" + i + "(path: string): string;").join("\n");
    const entry = join(dir, "index.ts");
    writeFileSync(entry, "export interface Engine {" + fields + " rawMemory: Uint8Array }\nexport declare function load(): Engine;\nexport default load;");
    const out = join(dir, "out");
    assert.equal(await main(["public-api-inputs", out, entry], { out: () => {} }), 0);
    const body = readFileSync(join(out, "1-index.ts.apisurface"), "utf8");
    assert.match(body, /rawMemory/);
    assert.match(body, /default — alias of load/);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

